@dataclass
class Params:
    """Гиперпараметры структурной модели. Значения по умолчанию выбраны по бэктесту (ml backtest)."""
    # уровень будня
    level_weeks: int = 3               # окно оценки уровня, недель
    level_estimator: str = "mean"      # mean | median | trim
    # отношения типов дня к будню (Вт–Чт)
    ratio_weeks: int = 6               # окно для Сб/Вс/Пн/Пт к будню
    weekday_shrink: float = 1.0        # Пн/Пт — сетевые (по маршрутам между периодами не воспроизводятся)
    stale_weeks: int = 6               # если свежих дней нужного режима нет дольше — берём зимнюю опору
    # суточный профиль
    profile_weeks: int = 4
    profile_estimator: str = "sum"     # sum (отношение сумм) | median (медиана долей)
    # сдвиг профиля и выходных к «зимней» форме (янв–мар): доля зимней опоры по месяцу прогноза.
    # На октябре α = 0.4 даёт +0.005 (фолд D) и +0.0015 (фолд E); дальше в зиму — больше.
    winter_alpha: dict = field(default_factory=lambda: {10: 0.4, 11: 0.5, 12: 0.6})
    winter_ref: tuple = ("2025-01-13", "2025-03-30")
    # аномальные дни (к медиане того же типа дня ±14 дней)
    anomaly_low: float = 0.6
    anomaly_high: float = 1.4
    # погода: коэффициенты оцениваются по истории до отсечки; это — фолбэк.
    # Выключена: на фолдах дневной множитель погоды не улучшает почасовой WAPE даже при оракульном уровне.
    # Остаётся сценарием/ползунком k_weather для UI.
    use_weather: bool = False
    precip_transform: str = "log1p"   # linear | log1p | cap10
    beta_default: dict = field(default_factory=lambda: {"precip": -0.0064, "snowfall": -0.018, "t_anom": 0.0047})
    # погода как перераспределение между днями внутри месяца (weather.redistribute): exp(β·log1p(осадки, мм)),
    # сумма месяца не меняется. Регрессия Jan–Oct даёт β ≈ −0.026 (t = −5.5), но вне выборки эффект вдвое слабее:
    # β = −0.012 улучшает все 5 фолдов (A +0.00045, B +0.00051, C +0.00008, D +0.00032, E +0.00015), −0.024 — вредит.
    # Лидерборд 27.09: β = −0.012 → 0.91238 (−0.00012 к 0.91250) — в ноябре–декабре не помогает, выключено.
    # Остаётся сценарным коэффициентом (py -m ml weather-probe --beta …)
    weather_beta: float = 0.0
    # календарные множители (раздел 7.5 исследования)
    # нерабочий будний = воскресенье × k. Лидерборд 26.09 (3–4.11): 0.85 = −0.00054, 1.05 = −0.00029 → оптимум ≈ 0.965
    hol_vs_sun: float = 0.95
    hol_profile: str = "satsun"        # sun | satsun (фолд B: satsun лучше)
    # рабочая сокращённая суббота 1.11 = будень × k, профиль пятницы.
    # Лидерборд 26.09 (к 0.75): 0.65 = −0.00163, 0.85 = +0.00071 → модель ошибки: оптимум ≈ 0.86
    worksat_vs_wd: float = 0.85
    pre_ny: dict = field(default_factory=lambda: {"2025-12-29": 0.90, "2025-12-30": 0.85})
    # 31.12 = суббота × k, профиль субботы. Лидерборд 26.09 (к 0.85): 0.70 = +0.00156, 1.00 = −0.00179
    # → модель ошибки: оптимум ≈ 0.53; проверено: 0.62 = 0.90687, 0.53 = 0.90693
    nye_vs_sat: float = 0.53
    short_vs_wd: float = 0.95          # предпраздничный сокращённый будний, профиль пятницы
    # общий множитель уровня: во всех осенне-зимних фолдах модель занижает (−1.7…−4.5 %),
    # лидерборд асимметричен (×0.97 = −0.0068, ×1.03 = +0.0001) → лёгкий сдвиг вверх; проверяется сабмитом
    # Лидерборд 26.09: ×1.00 = −0.00156, ×1.04 = −0.00159 к ×1.02 → оптимум ×1.02
    level_mult: float = 1.02
    # {месяц: множитель} поверх level_mult. Пробы: ноябрь ×1.04/1.02 = −0.00048 (к v2), декабрь ×0.98 = −0.00104 (к v8)
    # → оба месяца на оптимуме, поправок нет
    level_month: dict = field(default_factory=dict)
    # {маршрут: множитель} — калибровка по лидерборду (ml/calibrate.py). Пробы 26.09 к 0.90693:
    # 17 ×1.03 = −0.00230 → k* 0.975–0.991; 12 ×1.03 = −0.00097 → 0.977–0.993; 11 ×0.97 = −0.00142 → 1.022–1.050.
    # Берём осторожную сторону диапазона (σ шума × 0.85–1.0), чтобы не перелететь.
    # Пробы 27.09 к v5 (0.90749): 50 ×1.03 = +0.00034, 1 ×1.03 = +0.00041, 28 ×1.05 = +0.00045 (оптимумы 1.035/1.035/1.058),
    # 26 ×1.03 = +0.00009 (оптимум 1.019), 25 ×1.05 = −0.00083 (оптимум ≈ 0.93, берём осторожно 0.95).
    route_mult: dict = field(default_factory=lambda: {17: 0.985, 12: 0.987, 11: 1.033,
                                                      50: 1.03, 1: 1.03, 26: 1.02, 28: 1.05, 25: 0.95})

    def to_dict(self) -> dict:
        d = asdict(self)
        d["winter_alpha"] = {str(k): v for k, v in self.winter_alpha.items()}
        return d


